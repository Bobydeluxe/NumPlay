#!/usr/bin/env python3
"""Reproduce read-only tables/patterns and the launcher icon, offline."""
from pathlib import Path
import argparse
import hashlib
import io
import json
import re
from PIL import Image

ROOT=Path(__file__).resolve().parents[1]
FILES={'tables.bin':'5374abb64cfb9b5d961856c60166cedc55859164cf2b8867730e144fa2bdd594',
       'patterns.chr':'6ae7ffd9795d670954b76c19706d4f355b53f49c38a1da14027faee2c9266f10'}

def compact_rom(data):
    """Retain every original data directive, not a sample of observed reads.

    Dynamic area/enemy pointers use byte-sized indices (plus a two-byte area
    header). Keep a conservative 512-byte contiguous window at every possible
    root, including sub-areas. Metatile roots need at most 256 bytes. VRAM
    command streams are retained through all three terminator reads. Music
    remains contiguous through the end of the address space, with all timers.
    """
    manifest=(ROOT/'assets/data-ranges.json').read_text().encode()
    assert hashlib.sha256(manifest).hexdigest()=='9c64d77e2f38b343747540d03113eb898244649dc0d7cdb5e3e44eb85d575b15'
    spans=json.loads(manifest)
    symbols=json.loads((ROOT/'assets/symbols.json').read_text())
    def byte(addr):return data[addr-0x8000]
    def roots(lo,hi,count):
        return [byte(symbols[lo]+i)|(byte(symbols[hi]+i)<<8) for i in range(count)]
    for lo,hi,count,size in [('EnemyDataAddrLow','EnemyDataAddrHigh',34,512),
                             ('AreaDataAddrLow','AreaDataAddrHigh',34,512),
                             ('MetatileGraphics_Low','MetatileGraphics_High',4,256)]:
        for addr in roots(lo,hi,count):spans.append([addr,min(65536,addr+size)])
    for addr in roots('VRAM_AddrTable_Low','VRAM_AddrTable_High',19):
        if addr<0x8000:continue  # Writable VRAM buffers live in CPU RAM.
        end=addr
        while byte(end):
            count=byte(end+2)&63;count=count or 256
            end+=3+(1 if byte(end+2)&64 else count)
            assert end<65534,'Invalid original VRAM stream'
        spans.append([addr,end+3])
    spans.append([symbols['MusicHeaderData'],65536])
    merged=[]
    for start,end in sorted(spans):
        assert 0x8000<=start<end<=65536
        if merged and start<=merged[-1][1]+16:merged[-1][1]=max(end,merged[-1][1])
        else:merged.append([start,end])
    packed=bytearray();ranges=[]
    for start,end in merged:
        ranges.append((start,end,len(packed)));packed+=data[start-0x8000:end-0x8000]
    def offset(addr,size=1):
        for start,end,pos in ranges:
            if start<=addr and addr+size<=end:return pos+addr-start
        raise AssertionError(f'Noncontiguous ROM range ${addr:04x}+{size}')
    # Prove all declared constant tables remain contiguous, including the
    # upstream's deliberate one-byte envelope lookaheads.
    header=(ROOT/'vendor/smbcore/smb1_romarrays.h').read_text()
    constants={n:int(v) for n,v in re.findall(r'#define\s+(\w+_IntendedLength)\s+(\d+)',header)}
    for address,length in re.findall(r'RAMARRAY_CONST\(([^,]+),\s*([^\)]+)\)',header):
        for name,value in constants.items():length=length.replace(name,str(value))
        assert re.fullmatch(r'[0-9a-fA-FxX+\-\s]+',address+length)
        offset(eval(address,{'__builtins__':{}}),eval(length,{'__builtins__':{}}))
    lines=['/* Generated by tools/assets.py; original addresses mapped to flash. */',
           '#ifndef SMB_ROM_H','#define SMB_ROM_H','#include <stdint.h>',
           f'extern const uint8_t smb_rom[{len(packed)}];',
           'const uint8_t *smb_rom_address(uint16_t addr);',
           '#define SMB_ROM_OFFSET(addr) (\\']
    for start,end,pos in ranges:
        lines.append(f' ((addr)<0x{end:x}u) ? ((addr)-0x{start:x}u+{pos}u) : \\')
    lines+=[' 0u)','#endif']
    lookup=['const uint8_t *smb_rom_address(uint16_t addr) {',
            '  /* Binary search is used only when rebasing a dynamic ROM pointer. */',
            '  static const uint16_t starts[]={'+','.join(str(s) for s,e,p in ranges)+'};',
            '  static const uint16_t offsets[]={'+','.join(str(p) for s,e,p in ranges)+','+str(len(packed))+'};',
            f'  unsigned lo=0,hi={len(ranges)};',
            '  while(lo<hi) {unsigned mid=(lo+hi)/2;if(addr<starts[mid])hi=mid;else lo=mid+1;}',
            '  if(!lo)return 0;',
            '  unsigned i=lo-1,delta=addr-starts[i];',
            '  if(delta>=(unsigned)(offsets[i+1]-offsets[i]))return 0;',
            '  return smb_rom+offsets[i]+delta;','}']
    print(f'Original data retained in {len(ranges)} flash spans: {len(data)} -> {len(packed)} bytes')
    return bytes(packed),'\n'.join(lines)+'\n',lookup

def main():
    ap=argparse.ArgumentParser(description=__doc__);ap.add_argument('--check',action='store_true');args=ap.parse_args()
    lines=['/* Original Nintendo tables/patterns; see assets/README.md. */','#include "rom.h"']
    outputs={}
    for name,file in [('smb_rom','tables.bin'),('smb_patterns','patterns.chr')]:
        data=(ROOT/'assets'/file).read_bytes();assert hashlib.sha256(data).hexdigest()==FILES[file]
        if file=='tables.bin':
            data,header,lookup=compact_rom(data)
            outputs[ROOT/'src/rom.h']=header.encode()
        lines.append('const uint8_t '+name+'['+str(len(data))+'] = {')
        for i in range(0,len(data),24):lines.append(','.join(hex(v) for v in data[i:i+24])+',')
        lines.append('};')
        if file=='tables.bin':lines+=lookup
    icon=Image.new('RGBA',(55,56),'#5c94fc')
    mario=Image.open(ROOT/'assets/small-mario.png').convert('RGBA').resize((36,48),Image.Resampling.NEAREST)
    icon.alpha_composite(mario,(9,4));buf=io.BytesIO();icon.convert('RGB').save(buf,format='PNG',optimize=True)
    outputs.update({ROOT/'src/data.c':('\n'.join(lines)+'\n').encode(),ROOT/'src/icon.png':buf.getvalue()})
    for path,data in outputs.items():
        if args.check:assert path.read_bytes()==data,'Regenerate '+str(path)
        else:path.write_bytes(data)
    print('PASS: original data hashes and deterministic generated assets'+(' (check)' if args.check else ''))
if __name__=='__main__':main()
